/* ── GL state ── */
static GLuint s_texture  = 0;
static GLuint s_program  = 0;
static GLuint s_vbo      = 0;
static GLint  s_loc_proj = -1;
static GLint  s_loc_col  = -1;
static GLint  s_loc_tex  = -1;

/* Atlas layout: 16 chars wide × 6 rows, each char 8×8 px → 128×48 px */
#define ATLAS_COLS 16
#define ATLAS_ROWS 6
#define ATLAS_W   (ATLAS_COLS * 8)
#define ATLAS_H   (ATLAS_ROWS * 8)

static GLuint compile_shader(GLenum type, const char *src) {
    GLuint sh = glCreateShader(type);
    glShaderSource(sh, 1, &src, NULL);
    glCompileShader(sh);
    return sh;
}

void font_init(void) {
    /* Build luminance atlas */
    uint8_t pixels[ATLAS_H][ATLAS_W];
    memset(pixels, 0, sizeof(pixels));

    for (int ch = 0; ch < 96; ch++) {
        int ax = (ch % ATLAS_COLS) * 8;
        int ay = (ch / ATLAS_COLS) * 8;
        for (int row = 0; row < 8; row++) {
            uint8_t byte = FONT8X8[ch][row];
            for (int bit = 0; bit < 8; bit++)
                pixels[ay + row][ax + bit] = (byte & (0x80 >> bit)) ? 0xFF : 0x00;
        }
    }

    glGenTextures(1, &s_texture);
    glBindTexture(GL_TEXTURE_2D, s_texture);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_LUMINANCE, ATLAS_W, ATLAS_H,
                 0, GL_LUMINANCE, GL_UNSIGNED_BYTE, pixels);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glBindTexture(GL_TEXTURE_2D, 0);

    /* Shader program */
    const char *vs =
        "attribute vec2 a_pos;\n"
        "attribute vec2 a_uv;\n"
        "uniform mat4 u_proj;\n"
        "varying vec2 v_uv;\n"
        "void main(){\n"
        "  gl_Position = u_proj * vec4(a_pos, 0.0, 1.0);\n"
        "  v_uv = a_uv;\n"
        "}\n";

    const char *fs =
        "precision mediump float;\n"
        "uniform sampler2D u_tex;\n"
        "uniform vec4 u_col;\n"
        "varying vec2 v_uv;\n"
        "void main(){\n"
        "  float a = texture2D(u_tex, v_uv).r;\n"
        "  gl_FragColor = vec4(u_col.rgb, a * u_col.a);\n"
        "}\n";

    GLuint v = compile_shader(GL_VERTEX_SHADER,   vs);
    GLuint f = compile_shader(GL_FRAGMENT_SHADER, fs);
    s_program = glCreateProgram();
    glAttachShader(s_program, v);
    glAttachShader(s_program, f);
    glBindAttribLocation(s_program, 0, "a_pos");
    glBindAttribLocation(s_program, 1, "a_uv");
    glLinkProgram(s_program);
    glDeleteShader(v);
    glDeleteShader(f);

    s_loc_proj = glGetUniformLocation(s_program, "u_proj");
    s_loc_col  = glGetUniformLocation(s_program, "u_col");
    s_loc_tex  = glGetUniformLocation(s_program, "u_tex");

    glGenBuffers(1, &s_vbo);
}

void font_destroy(void) {
    if (s_texture) { glDeleteTextures(1, &s_texture); s_texture = 0; }
    if (s_program) { glDeleteProgram(s_program); s_program = 0; }
    if (s_vbo)     { glDeleteBuffers(1, &s_vbo); s_vbo = 0; }
}

/* Each character emits 6 vertices: position(2) + uv(2) = 4 floats */
#define MAX_CHARS 128
static float s_verts[MAX_CHARS * 6 * 4];

void font_draw_text(const char *text, float px, float py, float scale,
                    float r, float g, float b, float a,
                    const float proj[16]) {
    if (!s_program || !s_texture) return;

    int  len   = 0;
    float cx   = px;
    float cw   = 8.0f * scale;
    float ch_h = 8.0f * scale;
    float iaw  = 1.0f / ATLAS_W;
    float iah  = 1.0f / ATLAS_H;

    int n = 0;
    while (text[n] && n < MAX_CHARS) n++;

    int vi = 0;
    for (int i = 0; i < n; i++) {
        unsigned char c = (unsigned char)text[i];
        if (c < 32 || c > 127) { cx += cw; continue; }
        int idx = c - 32;
        int ax  = (idx % ATLAS_COLS) * 8;
        int ay  = (idx / ATLAS_COLS) * 8;
        float u0 = ax * iaw, u1 = (ax + 8) * iaw;
        float v0 = ay * iah, v1 = (ay + 8) * iah;
        float x0 = cx, x1 = cx + cw;
        float y0 = py, y1 = py + ch_h;
        /* 2 triangles */
        float quad[6][4] = {
            {x0,y0,u0,v0},{x1,y0,u1,v0},{x0,y1,u0,v1},
            {x1,y0,u1,v0},{x1,y1,u1,v1},{x0,y1,u0,v1}
        };
        for (int q = 0; q < 6; q++)
            for (int f2 = 0; f2 < 4; f2++)
                s_verts[vi++] = quad[q][f2];
        cx += cw;
        len++;
    }

    glUseProgram(s_program);
    glUniformMatrix4fv(s_loc_proj, 1, GL_FALSE, proj);
    glUniform4f(s_loc_col, r, g, b, a);
    glUniform1i(s_loc_tex, 0);

    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, s_texture);

    glBindBuffer(GL_ARRAY_BUFFER, s_vbo);
    glBufferData(GL_ARRAY_BUFFER, vi * sizeof(float), s_verts, GL_DYNAMIC_DRAW);

    glEnableVertexAttribArray(0);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4*sizeof(float), (void*)0);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4*sizeof(float), (void*)(2*sizeof(float)));

    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glDrawArrays(GL_TRIANGLES, 0, len * 6);

    glDisableVertexAttribArray(0);
    glDisableVertexAttribArray(1);
    glBindBuffer(GL_ARRAY_BUFFER, 0);
    glBindTexture(GL_TEXTURE_2D, 0);
}

float font_text_width(const char *text, float scale) {
    int n = 0;
    while (text[n]) n++;
    return n * 8.0f * scale;
}

float font_char_height(float scale) {
    return 8.0f * scale;
}
